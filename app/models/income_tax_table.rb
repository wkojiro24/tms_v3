  # 課税対象額と扶養人数から所得税額を取得
  def self.lookup(taxable_amount, dependents: 0, table_type: 'A')
    return 0 if taxable_amount <= 0

    dependents = [dependents.to_i, 0].max

    if table_type == 'A'
      lookup_table_a(taxable_amount, dependents)
    else
      lookup_table_b(taxable_amount)
    end
  end

  private

  def self.lookup_table_a(amount, dependents)
    row = TAX_TABLE_A.find { |r| amount >= r[0] && amount < r[1] }

    return calculate_high_income(amount, dependents) if row.nil?

    col_index = [dependents + 2, 9].min

    tax = row[col_index]

    if dependents > 7
      extra_dependents = dependents - 7
      tax = [tax - (extra_dependents * 1_610), 0].max
    end

    tax
  end

  def self.calculate_high_income(amount, dependents)
    base_tax = case amount
    when 551_000..708_000
      (amount * 0.2042 - 48_960).round
    when 708_001..1_169_000
      (amount * 0.2330 - 69_360).round
    when 1_169_001..1_737_000
      (amount * 0.3330 - 186_300).round
    when 1_737_001..3_688_000
      (amount * 0.4040 - 309_500).round
    else
      (amount * 0.4540 - 493_900).round
    end

    deduction = dependents * 1_610
    [base_tax - deduction, 0].max
  end

  def self.lookup_table_b(amount)
    (amount * 0.0358).round
  end
